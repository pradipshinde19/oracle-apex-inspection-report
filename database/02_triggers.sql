-- 1. Audit & Validation Triggers
CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_QA_COMPANY_AUDIT" 
BEFORE INSERT OR UPDATE ON "QA_COMPANY" FOR EACH ROW 
BEGIN 
    IF INSERTING THEN 
        :NEW.CREATED_BY := NVL(V('APP_USER'), USER); 
        :NEW.CREATED_ON := SYSTIMESTAMP; 
    END IF; 
    IF UPDATING THEN 
        :NEW.UPDATED_BY := NVL(V('APP_USER'), USER); 
        :NEW.UPDATED_ON := SYSTIMESTAMP; 
    END IF; 
END;
/

