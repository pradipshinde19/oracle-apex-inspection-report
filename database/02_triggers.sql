CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_BIU_QA_USER_PROFILE" 
BEFORE INSERT OR UPDATE ON "QA_USER_PROFILE" FOR EACH ROW  
BEGIN  
    IF INSERTING THEN  
        :NEW.USERNAME   := UPPER(TRIM(:NEW.USERNAME));  
        :NEW.CREATED    := CURRENT_TIMESTAMP;  
        :NEW.CREATED_BY := COALESCE(:NEW.CREATED_BY, QA_SECURITY_PKG.GET_CURRENT_USER);  
    END IF;  
    :NEW.UPDATED    := CURRENT_TIMESTAMP;  
    :NEW.UPDATED_BY := COALESCE(:NEW.UPDATED_BY, QA_SECURITY_PKG.GET_CURRENT_USER);  
END;
/
