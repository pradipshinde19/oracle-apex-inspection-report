INSERT INTO QA_CHECKLIST_RESULTS (
    RESULT_ID, SR_NO, COMP, DIV, TYPE_ID, MODEL_NAME,
    WORK_ORDER_NO, SERIAL_NO, SERIAL_NO_TO, INSPECT_DATE,
    INSPECTED_BY, CHECKLIST_ID, INSPECTED_YN, COMMENTS,
    FINAL_SAVE_FLAG, CREATED_BY, UPDATED_BY, CREATED_ON, UPDATED_ON
)
WITH REPORTS AS (
    SELECT 1 REPORT_NO, 31 TYPE_ID, 'Laptop' MODEL_NAME,
           DATE '2026-10-01' INSPECT_DATE FROM DUAL
    UNION ALL
    SELECT 2, 32, 'Desktop Computer',
           DATE '2026-10-01' FROM DUAL
    UNION ALL
    SELECT 3, 33, 'Mobile Phone',
           DATE '2026-10-01' FROM DUAL

    UNION ALL
    SELECT 4, 34, 'Office Chair',
           DATE '2026-10-05' FROM DUAL
    UNION ALL
    SELECT 5, 31, 'Laptop',
           DATE '2026-10-05' FROM DUAL

    UNION ALL
    SELECT 6, 32, 'Desktop Computer',
           DATE '2026-10-12' FROM DUAL
    UNION ALL
    SELECT 7, 33, 'Mobile Phone',
           DATE '2026-10-12' FROM DUAL
    UNION ALL
    SELECT 8, 34, 'Office Chair',
           DATE '2026-10-12' FROM DUAL

    UNION ALL
    SELECT 9, 31, 'Laptop',
           DATE '2026-10-21' FROM DUAL
    UNION ALL
    SELECT 10, 32, 'Desktop Computer',
           DATE '2026-10-29' FROM DUAL
),
CHECKLIST AS (
    SELECT '1' SR_NO, 512 CHECKLIST_ID FROM DUAL
    UNION ALL SELECT '2', 513 FROM DUAL
    UNION ALL SELECT '3', 514 FROM DUAL
    UNION ALL SELECT '4', 515 FROM DUAL
),
SEED_DATA AS (
    SELECT R.*, C.SR_NO, C.CHECKLIST_ID
    FROM REPORTS R
    CROSS JOIN CHECKLIST C
)
SELECT
    (SELECT NVL(MAX(RESULT_ID), 0)
       FROM QA_CHECKLIST_RESULTS)
      + ROW_NUMBER() OVER (
            ORDER BY REPORT_NO, TO_NUMBER(SR_NO)
        ) AS RESULT_ID,
    SR_NO,
    '1000',
    '1001',
    TYPE_ID,
    MODEL_NAME,
    TO_CHAR(2352525 + REPORT_NO),
    3525252 + REPORT_NO,
    NULL,
    INSPECT_DATE,
    'Pradip Shinde',
    CHECKLIST_ID,
    'Y',
    'Seed test data',
    'N',
    '14086',
    NULL,
    SYSTIMESTAMP,
    NULL
FROM SEED_DATA;

COMMIT;
