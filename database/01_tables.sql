BEGIN
    FOR T IN (
        SELECT 'QA_CHECKLIST_MASTER' TABLE_NAME FROM DUAL UNION ALL
        SELECT 'QA_ROLE_ASSIGNMENTS' FROM DUAL UNION ALL
        SELECT 'QA_DIVISION' FROM DUAL UNION ALL
        SELECT 'QA_INSPECTION_IMAGES' FROM DUAL UNION ALL
        SELECT 'QA_APEX_TEMP' FROM DUAL UNION ALL
        SELECT 'QA_CHECKLIST_RESULTS' FROM DUAL UNION ALL
        SELECT 'QA_USER_PROFILE' FROM DUAL UNION ALL
        SELECT 'QA_SET_TYPES' FROM DUAL UNION ALL
        SELECT 'QA_ROLES' FROM DUAL UNION ALL
        SELECT 'QA_COMPANY' FROM DUAL
    )
    LOOP
        BEGIN
            EXECUTE IMMEDIATE
                'DROP TABLE ' || T.TABLE_NAME || ' CASCADE CONSTRAINTS PURGE';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
